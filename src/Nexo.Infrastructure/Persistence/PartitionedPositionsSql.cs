namespace Nexo.Infrastructure.Persistence;

/// <summary>SQL da tabela de posições dividida em uma partição por mês de referência.</summary>
/// <remarks>Com partições, gravar um mês novo custa o mesmo com 1 ou 100 meses no banco.</remarks>
internal static class PartitionedPositionsSql
{
    // O EF não sabe criar tabela particionada, então a migration usa este SQL no lugar do CreateTable.
    // O PostgreSQL exige que a chave primária inclua a coluna usada para dividir (reference_date).
    // Sem chaves estrangeiras de propósito: elas eram 80% do tempo de gravação (medido: 132 s contra 27 s
    // por mês). A carga já garante a ligação, gravando carteira, ativo e posição na mesma transação.
    public const string CreateTable = """
        CREATE TABLE positions (
            id bigint GENERATED BY DEFAULT AS IDENTITY,
            reference_date date NOT NULL,
            portfolio_id bigint NOT NULL,
            asset_id bigint NULL,
            is_confidential boolean NOT NULL,
            block smallint NULL,
            application_type text NOT NULL,
            asset_type text NULL,
            trading_intent text NULL,
            issuer_is_related boolean NULL,
            quantity numeric NULL,
            market_value numeric NULL,
            cost_value numeric NULL,
            bought_quantity numeric NULL,
            bought_value numeric NULL,
            sold_quantity numeric NULL,
            sold_value numeric NULL,
            share_of_net_worth numeric NULL,
            confidential_until date NULL,
            details jsonb NULL,
            CONSTRAINT pk_positions PRIMARY KEY (id, reference_date)
        ) PARTITION BY RANGE (reference_date);
        """;

    // Cria a partição do mês (ex.: positions_202609) se ela ainda não existir. A carga chama antes de gravar.
    public const string CreatePartitionFunction = """
        CREATE OR REPLACE FUNCTION ensure_positions_partition(month date) RETURNS void
        LANGUAGE plpgsql AS $$
        DECLARE
            first_day date := date_trunc('month', month)::date;
        BEGIN
            EXECUTE format(
                'CREATE TABLE IF NOT EXISTS %I PARTITION OF positions FOR VALUES FROM (%L) TO (%L)',
                'positions_' || to_char(first_day, 'YYYYMM'),
                first_day,
                (first_day + interval '1 month')::date);
        END $$;
        """;

    public const string DropPartitionFunction = "DROP FUNCTION IF EXISTS ensure_positions_partition(date);";
}
