namespace Nexo.Infrastructure.Persistence;

/// <summary>SQL da tabela de posições dividida em uma partição por mês de referência.</summary>
/// <remarks>Com partições, gravar um mês novo custa o mesmo com 1 ou 100 meses no banco.</remarks>
internal static class PartitionedPositionsSql
{
    // O EF não sabe criar tabela particionada, então a migration usa este SQL no lugar do CreateTable.
    // O PostgreSQL exige que a chave primária inclua a coluna usada para dividir (reference_date).
    // Sem chaves estrangeiras na tabela-mãe: conferir linha a linha era 80% do tempo de gravação (medido:
    // 132 s contra 27 s por mês). Cada partição ganha as chaves depois da carga (ver CreateForeignKeysFunction).
    public const string CreateTable = """
        CREATE TABLE positions (
            id bigint GENERATED BY DEFAULT AS IDENTITY,
            reference_date date NOT NULL,
            portfolio_id bigint NOT NULL,
            asset_id bigint NULL,
            is_confidential boolean NOT NULL,
            block smallint NULL,
            application_type text NOT NULL,
            asset_type text NULL,
            trading_intent text NULL,
            issuer_is_related boolean NULL,
            quantity numeric NULL,
            market_value numeric NULL,
            cost_value numeric NULL,
            bought_quantity numeric NULL,
            bought_value numeric NULL,
            sold_quantity numeric NULL,
            sold_value numeric NULL,
            share_of_net_worth numeric NULL,
            confidential_until date NULL,
            details jsonb NULL,
            CONSTRAINT pk_positions PRIMARY KEY (id, reference_date)
        ) PARTITION BY RANGE (reference_date);
        """;

    // Cria a partição do mês (ex.: positions_202609) se ela ainda não existir. A carga chama antes de gravar.
    public const string CreatePartitionFunction = """
        CREATE OR REPLACE FUNCTION ensure_positions_partition(month date) RETURNS void
        LANGUAGE plpgsql AS $$
        DECLARE
            first_day date := date_trunc('month', month)::date;
        BEGIN
            EXECUTE format(
                'CREATE TABLE IF NOT EXISTS %I PARTITION OF positions FOR VALUES FROM (%L) TO (%L)',
                'positions_' || to_char(first_day, 'YYYYMM'),
                first_day,
                (first_day + interval '1 month')::date);
        END $$;
        """;

    public const string DropPartitionFunction = "DROP FUNCTION IF EXISTS ensure_positions_partition(date);";

    // Liga as posições do mês à carteira e ao ativo, conferindo o mês inteiro de uma vez só (VALIDATE), depois
    // que a carga terminou. Pode ser chamada de novo: chave que já existe é só conferida, e isso não custa nada.
    public const string CreateForeignKeysFunction = """
        CREATE OR REPLACE FUNCTION ensure_positions_foreign_keys(month date) RETURNS void
        LANGUAGE plpgsql AS $$
        DECLARE
            partition_name text := 'positions_' || to_char(date_trunc('month', month), 'YYYYMM');
            link record;
            key_name text;
        BEGIN
            IF to_regclass(partition_name) IS NULL THEN
                RETURN;
            END IF;

            FOR link IN SELECT * FROM (VALUES ('portfolio_id', 'portfolios'), ('asset_id', 'assets')) AS links(column_name, target) LOOP
                key_name := format('fk_%s_%s', partition_name, link.target);

                IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = partition_name::regclass AND conname = key_name) THEN
                    BEGIN
                        EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY (%I) REFERENCES %I (id) NOT VALID',
                            partition_name, key_name, link.column_name, link.target);
                    EXCEPTION WHEN duplicate_object THEN
                        NULL; -- outro worker criou a mesma chave ao mesmo tempo
                    END;
                END IF;

                EXECUTE format('ALTER TABLE %I VALIDATE CONSTRAINT %I', partition_name, key_name);
            END LOOP;
        END $$;
        """;

    // Usado pela migração: as partições que já existiam ganham as chaves de uma vez.
    public const string AddForeignKeysToExistingPartitions = """
        SELECT ensure_positions_foreign_keys(to_date(right(child.relname, 6), 'YYYYMM'))
        FROM pg_inherits
        JOIN pg_class child ON child.oid = pg_inherits.inhrelid
        WHERE pg_inherits.inhparent = 'positions'::regclass;
        """;

    public const string DropForeignKeys = """
        DO $$
        DECLARE key record;
        BEGIN
            FOR key IN SELECT conrelid::regclass AS partition_name, conname FROM pg_constraint
                       WHERE contype = 'f' AND conname LIKE 'fk_positions_%' LOOP
                EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I', key.partition_name, key.conname);
            END LOOP;
        END $$;
        DROP FUNCTION IF EXISTS ensure_positions_foreign_keys(date);
        """;
}
